void drawMap(SDL_Renderer* renderer){
		for (int y = 0; y < MAPSIZE; y++){
				for (int x = 0; x < MAPSIZE; x++){
							if (demoMap[y][x] == 1){
								cells["Wall"].draw(renderer,
												x * cSize,
												y * cSize);
							}
				}
		}

		SDL_SetRenderDrawColor(renderer, 0x66, 0x66, 0x66, 0xFF);
		for (int y = 0; y < MAPSIZE; y++){

				int yy = y*cSize;
				SDL_RenderLine(renderer, 
								0, 
								yy, 
								MAPSIZE * cSize,
								yy);
		}

		for (int x = 0; x < MAPSIZE; x++){
				int xx = x * cSize;
				SDL_RenderLine(renderer,
								xx,
								0,
								xx,
								MAPSIZE * cSize);
		}



}

